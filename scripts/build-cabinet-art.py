def lettering(rects, key):
    # Nested viewports crop only the lettering and keep its original type.
    # Local CSS contrast clears the source paper without shared SVG filters.
    return ''.join(
        f'<svg x="{x}" y="{y}" width="{w}" height="{h}" viewBox="{x} {y} {w} {h}" overflow="hidden"><image xlink:href="./images/archive-cabinet.png" width="1121" height="1403" style="filter:brightness(1.6) contrast(2)"/></svg>'
        for x, y, w, h in rects
    )

# Every folder is a closed shape that continues behind the front cover.
# The lower edge stays occluded throughout the complete hover movement.
